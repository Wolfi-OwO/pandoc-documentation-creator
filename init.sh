#!/bin/bash

set -e

# Pandoc Documentation Creator - Initialization Script
# This script sets up the documentation project structure

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
IMAGE_REGISTRY="registry.gitlab.com/woofi4/public/pandoc-documentation-creator"
VERSION="unknown"
IMAGE_TAG=""

# Repository URL for templates (updated after image version detection)
REPO_RAW_URL="https://gitlab.com/woofi4/public/pandoc-documentation-creator/-/raw/main/templates"

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

# Function to print colored messages
print_header() {
    echo -e "${BLUE}=======================================${NC}"
    echo -e "${BLUE}$1${NC}"
    echo -e "${BLUE}=======================================${NC}"
    echo ""
}

print_success() {
    echo -e "${GREEN}✓ $1${NC}"
}

print_error() {
    echo -e "${RED}✗ $1${NC}"
}

print_info() {
    echo -e "${YELLOW}→ $1${NC}"
}

# Function to check if command exists
command_exists() {
    command -v "$1" >/dev/null 2>&1
}

normalize_line_endings() {
    local file="$1"

    if [ -z "${file}" ] || [ ! -f "${file}" ]; then
        return 0
    fi

    if command_exists perl; then
        perl -pi -e 's/\r$//' "${file}"
        return 0
    fi

    if command_exists sed; then
        if sed -i 's/\r$//' "${file}" 2>/dev/null; then
            return 0
        fi
        sed -i '' 's/\r$//' "${file}" 2>/dev/null || true
        return 0
    fi
}

is_interactive() {
    [ -t 0 ] && [ -t 1 ]
}

prompt_with_default() {
    local prompt="$1"
    local default_value="$2"
    local __resultvar="$3"
    local input=""

    if is_interactive; then
        read -r -p "${prompt} [${default_value}]: " input
        input="${input:-${default_value}}"
    else
        input="${default_value}"
    fi

    printf -v "${__resultvar}" '%s' "${input}"
}

escape_double_quotes() {
    printf '%s' "$1" | sed 's/"/\\"/g'
}

to_container_paths() {
    local input_files="$1"
    local converted=""
    local token

    if [ -z "${input_files}" ]; then
        echo ""
        return 0
    fi

    for token in ${input_files}; do
        if [[ "${token}" == /* ]]; then
            converted+="${token} "
        else
            converted+="/data/${token} "
        fi
    done

    echo "${converted% }"
}

apply_user_config_to_build_script() {
    local build_script="$1"
    local output_name="$2"
    local input_files="$3"

    local esc_output_name
    local esc_input_files

    esc_output_name="$(escape_double_quotes "${output_name}")"
    esc_input_files="$(escape_double_quotes "${input_files}")"

    if grep -q "BEGIN USER CONFIG" "${build_script}"; then
        sed -i '/BEGIN USER CONFIG/,/END USER CONFIG/d' "${build_script}"
    fi

    local config_block
    config_block=$(cat <<EOF
# BEGIN USER CONFIG (generated by init.sh)
if [ -n "${esc_output_name}" ]; then
    OUTPUT_NAME="${esc_output_name}"
fi
if [ -n "${esc_input_files}" ]; then
    INPUT_FILES="${esc_input_files}"
fi
# END USER CONFIG
EOF
)

    local tmp_file="${build_script}.tmp"
    awk -v block="${config_block}" '
        { print }
        $0 ~ /^set -e$/ && !inserted { print ""; print block; inserted=1 }
    ' "${build_script}" > "${tmp_file}" && mv "${tmp_file}" "${build_script}"
}

CONFIG_OUTPUT_NAME=""
CONFIG_INPUT_FILES=""
CONFIG_INPUT_DIR=""
CONFIG_INPUT_FILES_CONTAINER=""

normalize_input_dir() {
    local input_files="$1"
    local first_token
    local dir

    first_token="${input_files%% *}"
    if [ -z "${first_token}" ]; then
        echo "chapters"
        return 0
    fi

    if [[ "${first_token}" == */* ]]; then
        dir="${first_token%/*}"
    else
        dir="."
    fi

    dir="${dir#./}"
    dir="${dir#/}"

    if [ -z "${dir}" ]; then
        echo "."
    else
        echo "${dir}"
    fi
}

display_input_dir() {
    local dir="$1"

    if [ -z "${dir}" ] || [ "${dir}" = "." ]; then
        echo "project root"
    else
        echo "${dir}/"
    fi
}

prompt_build_configuration() {
    local target_dir="$1"

    print_header "Build Configuration"
    print_info "Configure output name and input markdown files."
    echo ""

    local output_name
    local input_files

    prompt_with_default "Output PDF name (without .pdf)" "documentation" output_name
    prompt_with_default "Input files (space-separated, relative to project root)" "chapters/*.md" input_files

    CONFIG_OUTPUT_NAME="${output_name}"
    CONFIG_INPUT_FILES="${input_files}"
    CONFIG_INPUT_DIR="$(normalize_input_dir "${input_files}")"
    CONFIG_INPUT_FILES_CONTAINER="$(to_container_paths "${input_files}")"
}

# Function to download file from templates directory or use local
download_or_copy_template() {
    local template_name="$1"
    local destination="$2"
    
    # First try to copy from local templates directory
    if [ -f "${SCRIPT_DIR}/../templates/${template_name}" ]; then
        cp "${SCRIPT_DIR}/../templates/${template_name}" "${destination}"
        return 0
    fi
    
    # Try wget
    if command_exists wget; then
        wget -q -O "${destination}" "${REPO_RAW_URL}/${template_name}" 2>/dev/null && return 0
    fi
    
    # Try curl
    if command_exists curl; then
        curl -s -o "${destination}" "${REPO_RAW_URL}/${template_name}" 2>/dev/null && return 0
    fi
    
    return 1
}

create_new_project() {
    local target_dir="${1:-.}"
    local docs_dir
    local docs_display
    local docs_full_dir
    
    print_header "Creating New Documentation Project"

    # Prompt for configuration first (needed for directory setup)
    prompt_build_configuration "${target_dir}"

    docs_dir="${CONFIG_INPUT_DIR}"
    docs_display="$(display_input_dir "${docs_dir}")"
    if [ -n "${docs_dir}" ] && [ "${docs_dir}" != "." ]; then
        docs_full_dir="${target_dir}/${docs_dir}"
    else
        docs_full_dir="${target_dir}"
    fi
    
    # Create directory structure
    print_info "Creating directory structure..."
    if [ -n "${docs_dir}" ] && [ "${docs_dir}" != "." ]; then
        mkdir -p "${target_dir}/${docs_dir}"
    fi
    mkdir -p "${target_dir}/media"
    mkdir -p "${target_dir}/out"
    mkdir -p "${target_dir}/out/build"
    mkdir -p "${target_dir}/.vscode"
    mkdir -p "${target_dir}/.vscode/schemas"
    print_success "Directories created"
    
    # Copy or download configuration files
    print_info "Setting up configuration..."
    
    # Metadata only (defaults.yaml is built into Docker image)
    if download_or_copy_template "metadata.yaml.template" "${target_dir}/metadata.yaml"; then
        normalize_line_endings "${target_dir}/metadata.yaml"
        print_success "Created metadata.yaml"
    else
        print_error "Failed to create metadata.yaml from templates"
        exit 1
    fi
    
    # Example chapters
    print_info "Creating example chapters..."
    
    if download_or_copy_template "01-introduction.md.template" "${docs_full_dir}/01-introduction.md"; then
        if [ -n "${docs_dir}" ]; then
            sed -i "s#{{DOCS_DIR}}#${docs_dir}#g" "${docs_full_dir}/01-introduction.md" || true
        fi
        normalize_line_endings "${docs_full_dir}/01-introduction.md"
        print_success "Created ${docs_display}01-introduction.md"
    else
        print_error "Failed to create introduction from templates"
        exit 1
    fi

    if download_or_copy_template "02-example-content.md.template" "${docs_full_dir}/02-example-content.md"; then
        normalize_line_endings "${docs_full_dir}/02-example-content.md"
        print_success "Created ${docs_display}02-example-content.md"
    else
        print_error "Failed to create example content from templates"
        exit 1
    fi
    
    # Build helper script
    print_info "Creating build helper script..."
    if download_or_copy_template "buildPDF.template" "${target_dir}/buildPDF"; then
        chmod a+x "${target_dir}/buildPDF"
        if [ -n "${CONFIG_OUTPUT_NAME}" ] || [ -n "${CONFIG_INPUT_FILES_CONTAINER}" ]; then
            apply_user_config_to_build_script "${target_dir}/buildPDF" \
                "${CONFIG_OUTPUT_NAME}" \
                "${CONFIG_INPUT_FILES_CONTAINER}"
        fi
        if [ -n "${docs_dir}" ]; then
            sed -i "s#{{DOCS_DIR}}#${docs_dir}#g" "${target_dir}/buildPDF" || true
        fi
        normalize_line_endings "${target_dir}/buildPDF"
        chmod +x "${target_dir}/buildPDF"
        print_success "Created buildPDF"
    else
        print_error "Failed to create buildPDF from templates"
        exit 1
    fi
    
    # Help file
    print_info "Creating help documentation..."
    if download_or_copy_template "Help.md.template" "${target_dir}/Help.md"; then
        if [ -n "${IMAGE_TAG}" ]; then
            sed -i "s#\${IMAGE_TAG}#${IMAGE_TAG}#g" "${target_dir}/Help.md" || true
            sed -i "s#\${VERSION}#${IMAGE_TAG}#g" "${target_dir}/Help.md" || true
        fi
        if [ -n "${docs_dir}" ]; then
            sed -i "s#{{DOCS_DIR}}#${docs_dir}#g" "${target_dir}/Help.md" || true
        fi
        if [ -n "${CONFIG_OUTPUT_NAME}" ]; then
            sed -i "s#{{OUTPUT_NAME}}#${CONFIG_OUTPUT_NAME}#g" "${target_dir}/Help.md" || true
        fi
        normalize_line_endings "${target_dir}/Help.md"
        print_success "Created Help.md"
    else
        print_error "Failed to create Help.md from templates"
        exit 1
    fi

    print_info "Adding pandoc-schema for .yaml files..."
    if download_or_copy_template "pandoc-metadata.json.template" "${target_dir}/.vscode/schemas/pandoc-metadata.json"; then
        normalize_line_endings "${target_dir}/.vscode/schemas/pandoc-metadata.json"
        print_success "Created schema template"
    fi

    if download_or_copy_template "settings.json.template" "${target_dir}/.vscode/settings.json"; then
        normalize_line_endings "${target_dir}/.vscode/settings.json"
        print_success "Created vscode-settings"
    fi
    
    # Create .gitignore
    if download_or_copy_template "gitignore.template" "${target_dir}/.gitignore"; then
        normalize_line_endings "${target_dir}/.gitignore"
        print_success "Created .gitignore"
    else
        print_error "Failed to create .gitignore from templates"
        exit 1
    fi

    # Create .gitattributes (line endings)
    if download_or_copy_template "gitattributes.template" "${target_dir}/.gitattributes"; then
        normalize_line_endings "${target_dir}/.gitattributes"
        print_success "Created .gitattributes"
    else
        print_error "Failed to create .gitattributes from templates"
        exit 1
    fi
    
    echo ""
    print_success "Project structure created successfully!"
    echo ""
    print_header "Next Steps"
    echo "1. Edit your documentation in the ${docs_display}directory"
    echo "2. Customize document settings in metadata.yaml"
    echo "3. Run the Docker image and execute /data/buildPDF to generate your PDF"
    echo "4. Check Help.md for detailed documentation"
    echo ""
    echo "Note: Pandoc configuration (defaults.yaml) is built into the Docker image."
    echo "      You only need to edit metadata.yaml for document customization."
    echo ""
}

pull_with_spinner() {
    local image="$1"
    local pid
    local spin="|/-\\"
    local i=0

    docker pull "$image" >/dev/null 2>&1 &
    pid=$!

    printf "Pulling Docker image "
    while kill -0 "$pid" 2>/dev/null; do
        i=$(( (i+1) %4 ))
        printf "\rPulling Docker image %s" "${spin:$i:1}"
        sleep 0.1
    done
    wait "$pid"
    return $?
}

# Function to check/pull Docker image
check_docker_image() {
    print_header "Checking Docker Image"
    
    # Check Docker
    if ! command_exists docker; then
        print_error "Docker is not installed"
        exit 1
    fi
    
    # Try to pull the latest image
    print_info "Pulling latest Docker image..."
    if pull_with_spinner "${IMAGE_REGISTRY}:latest"; then
        print_success "Docker image pulled successfully"
    else
        print_error "Failed to pull Docker image"
        print_info "Checking for local image..."
        if ! docker image inspect "${IMAGE_REGISTRY}:latest" >/dev/null 2>&1; then
            print_error "No local image found either"
            exit 1
        fi
        print_info "Using local image"
    fi
    
        # Get version from Docker image
        IMAGE_VERSION=$(docker inspect --format='{{index .Config.Labels "org.opencontainers.image.version"}}' "${IMAGE_REGISTRY}:latest" 2>/dev/null || echo "unknown")
        
        if [ "$IMAGE_VERSION" != "unknown" ] && [ -n "$IMAGE_VERSION" ]; then
            VERSION="$IMAGE_VERSION"
            print_info "Using image version: ${VERSION}"
        else
            print_info "Could not determine image version, using default: ${VERSION}"
        fi

    if [ -n "${VERSION}" ] && [ "${VERSION}" != "unknown" ]; then
        IMAGE_TAG="${VERSION#v}"
    else
        IMAGE_TAG=""
    fi

    if [ -n "${VERSION}" ] && [ "${VERSION}" != "unknown" ]; then
        local repo_ref="${VERSION}"
        # If VERSION is a short/long git SHA, use it directly without a "v" prefix.
        if [[ "${VERSION}" =~ ^[0-9a-fA-F]{7,40}$ ]]; then
            repo_ref="${VERSION}"
        elif [[ "${VERSION}" == v* ]]; then
            repo_ref="${VERSION}"
        else
            # Non-prefixed tag (e.g., 1.2.3) uses v-prefixed ref.
            repo_ref="v${VERSION}"
        fi

        REPO_RAW_URL="https://gitlab.com/woofi4/public/pandoc-documentation-creator/-/raw/${repo_ref}/templates"
        print_info "Using templates from: ${REPO_RAW_URL}"
    fi
    
    # Set the full image name with version if available
    if [ -n "${IMAGE_TAG}" ]; then
        IMAGE_NAME="${IMAGE_REGISTRY}:${IMAGE_TAG}"
    else
        IMAGE_NAME="${IMAGE_REGISTRY}:latest"
    fi
    print_info "Selected image: ${IMAGE_NAME}"
}

# Main script logic
print_header "Pandoc Documentation Creator"

# Check/pull Docker image
check_docker_image

echo ""
print_info "Version: ${VERSION}"

echo ""

# Create new project structure
create_new_project "."

echo ""
print_header "Setup Complete!"
echo "Your documentation project is ready."
echo ""
echo "Next steps:"
echo "  1. Edit files in the chapters/ directory"
echo "  2. Customize metadata.yaml"
echo "  3. Run the Docker image and execute /data/buildPDF to generate your PDF"
echo ""

# Remove the init script
rm -rf init.sh
